-- Additive moderation metadata. No educational content, access, attempts,
-- answers, progress or existing history is changed by this migration.
CREATE TABLE `TaskReport` (
  `id` VARCHAR(191) NOT NULL,
  `reporterId` VARCHAR(191) NOT NULL,
  `taskId` VARCHAR(191) NOT NULL,
  `taskVersionId` VARCHAR(191) NOT NULL,
  `attemptId` VARCHAR(191) NULL,
  `requestKey` CHAR(36) NOT NULL,
  `category` ENUM('QUESTION', 'ANSWER', 'SOLUTION', 'DIAGRAM', 'FORMATTING', 'OTHER') NOT NULL,
  `message` TEXT NOT NULL,
  `status` ENUM('OPEN', 'IN_REVIEW', 'RESOLVED', 'DISMISSED') NOT NULL DEFAULT 'OPEN',
  `resolution` TEXT NULL,
  `revision` INTEGER NOT NULL DEFAULT 0,
  `reviewerId` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `reviewedAt` DATETIME(3) NULL,
  UNIQUE INDEX `TaskReport_reporterId_requestKey_key` (`reporterId`, `requestKey`),
  INDEX `TaskReport_status_createdAt_idx` (`status`, `createdAt`),
  INDEX `TaskReport_reporterId_createdAt_idx` (`reporterId`, `createdAt`),
  INDEX `TaskReport_taskId_idx` (`taskId`),
  INDEX `TaskReport_taskVersionId_idx` (`taskVersionId`),
  INDEX `TaskReport_reviewerId_idx` (`reviewerId`),
  INDEX `TaskReport_attemptId_idx` (`attemptId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `TaskReport_reporterId_fkey` FOREIGN KEY (`reporterId`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `TaskReport_reviewerId_fkey` FOREIGN KEY (`reviewerId`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `TaskReport_taskId_fkey` FOREIGN KEY (`taskId`) REFERENCES `Task` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `TaskReport_taskVersionId_fkey` FOREIGN KEY (`taskVersionId`) REFERENCES `TaskVersion` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `TaskReport_attemptId_fkey` FOREIGN KEY (`attemptId`) REFERENCES `Attempt` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
